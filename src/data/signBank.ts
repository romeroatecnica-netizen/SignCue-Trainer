export function resolveVisualForSystem(item: SignItem, system: SignSystem) {
  const variant = item.systemVariants?.[system];
  if (!variant) {
    return item.visual;
  }
  return {
    ...item.visual,
    ...variant,
    fingers: variant.fingers ? {...item.visual.fingers, ...variant.fingers} : item.visual.fingers,
  };
}

export function getSignById(id: string): SignItem | undefined {
  return SIGN_BANK.find((item) => item.id === id);
}

export function getLetterSign(letter: string): SignItem | undefined {
  const upper = letter.toUpperCase();
  return SIGN_BANK.find((item) => item.category === 'letters' && item.label === upper);
}
